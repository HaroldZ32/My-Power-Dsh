/** Parsed CLI options: where to install, whether to overwrite, and which mode to run. */
interface CliOptions {
  /** The explicit `--hooks-dir` target, or null to resolve the repository's own hooks directory. */
  hooksDir: string | null
  /** Whether `--force` was passed; an existing hook is otherwise refused and nothing is written. */
  force: boolean
  /** Whether `--self-test` was passed; every arm then runs in throwaway repos. */
  selfTest: boolean
}

/** Parse the CLI arguments and run the selected mode; returns the process exit code. */
function main(argv: readonly string[]): number {
  // `opts` is the parsed option set, mutated in place as each flag is read.
  const opts: CliOptions = { hooksDir: null, force: false, selfTest: false }
  // `i` walks the argv while `--hooks-dir`/`--member`-style flags consume the token after them.
  for (let i = 0; i < argv.length; i++) {
    // `arg` is the flag being read at this position.
    const arg: string = argv[i]
    if (arg === "--hooks-dir") {
      // `next` is the directory argument; a missing or flag-shaped value is refused, not guessed.
      const next: string | null = argv[++i] ?? null
      if (next === null || next.startsWith("--")) throw new Refusal("--hooks-dir needs a directory argument")
      opts.hooksDir = next
    } else if (arg === "--force") opts.force = true
    else if (arg === "--self-test") opts.selfTest = true
    else if (arg === "--help" || arg === "-h") {
      console.log(USAGE)
      return 0
    } else throw new Refusal(`unknown argument ${JSON.stringify(arg)}`)
  }
  if (opts.selfTest) {
    if (opts.hooksDir !== null) console.log(`${TAG} --self-test ignores --hooks-dir by design: every arm uses a throwaway dir`)
    return runSelfTest()
  }
  // `resolved` is the directory this run installs into, plus the rule that chose it.
  const resolved: HooksLocation = opts.hooksDir !== null ? { dir: opts.hooksDir, via: "--hooks-dir" } : resolveRealHooksDir()
  console.log(`${TAG} hooks dir: ${resolved.dir} (${resolved.via})`)
  installHook(resolved.dir, { force: opts.force })
  console.log(`${TAG} the guard refuses a staged ${CORPUS_PREFIX}** change without a staged ${LOCK_NAME}; it never re-pins`)
  return 0
}

try {
  process.exitCode = main(process.argv.slice(2))
} catch (e) {
  if (e instanceof Refusal) {
    console.log(`${TAG} REFUSED: ${e.message}`)
    process.exitCode = 1
  } else {
    throw e
  }
}
