/** The CLI entry point: dispatch one command, or print usage and fail on an unknown one. */
async function main(): Promise<void> {
  /** The command-line arguments after the script path. */
  const argv = process.argv.slice(2)
  /** The requested command. */
  const command = argv[0]
  /** Read `--<name>`'s value: the next argument, or `undefined` when the flag is absent or last. */
  const flag = (name: string): string | undefined => {
    /** Position of the flag in the argument list, or -1. */
    const index = argv.indexOf(name)
    return index === -1 ? undefined : argv[index + 1]
  }
  if (command === "--self-test") return selfTest()
  if (command === "--validator") {
    line(`[mpd-ext] validator: ${validator.mode}`)
    /** The paths the loaded validator came from: the compiled entry, or every source target. */
    const target = validator.mode === "compiled" ? [COMPILED_VALIDATOR] : Object.values(SOURCE_VALIDATOR)
    for (const rel of target) line(`  ${resolve(repoRoot, rel.replace(/^\.\.\//, ""))}`)
    if (validator.mode === "compiled") for (const attempt of validator.attempts) line(`  (source path unavailable: ${attempt.target}: ${attempt.error})`)
    return
  }
  if (command === "validate") {
    /** `--plane` as typed, before the membership test decides whether it is a plane at all. */
    const requestedPlane = flag("--plane")
    // The membership test is the runtime check the original ran; `includes` cannot narrow a string to the
    // plane union, so the value that test just approved is carried in one assertion (and free text, being
    // absent from PLANES, still falls to "user" — the runtime behaviour is unchanged).
    const candidate = requestedPlane as MpdExtensionPlane
    /** The plane to validate against: a requested plane, else the documented "user" default. */
    const plane: MpdExtensionPlane = PLANES.includes(candidate) ? candidate : "user"
    return runValidate(argv[1], plane)
  }
  if (command === "scaffold") {
    return runScaffold(argv[1], { dir: flag("--dir"), withMcp: argv.includes("--with-mcp") })
  }
  if (command === "list") return runList()
  line(USAGE)
  if (command !== undefined && command !== "help" && command !== "--help") process.exitCode = 2
}

await main()
