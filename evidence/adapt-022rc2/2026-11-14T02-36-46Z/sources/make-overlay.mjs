// T1 — render the SIX-row overlay that the two mount arms boot.
//
// The overlay is exactly D4's row shape: three legacy rows (their shipped names + configs) and three
// rc.2 rows (literal new names, `{ maxTasks: 256 }` on the first and NO `config:` key on the other
// two). Rows 1-2 carry the shipped TUI-plane clause composed with the generation half; row 3 carries
// the generation half alone. A probe row rides last so it activates after everything it observes.
//
// `--no-tui-clause` renders the EXPERIMENT variant whose rc.2 rows 1-2 have NO TUI-plane clause; the
// TUI arm uses it to measure whether the rc.2 team packages still need that clause.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { composeTuiAndGeneration, hazardOf, readTuiClause, renderGuard } from "./predicate.mjs";

const ROOT = dirname(new URL(import.meta.url).pathname);
const REPO = join(ROOT, "..", "..");

/**
 * @param id Row id.
 * @param name The plugin package specifier (literal; F8 forbids `!!js` names).
 * @param guard The `disabled:` expression, or `null` for no key.
 * @param config The config block lines, or `null` for NO `config:` key at all.
 * @param note A YAML comment line above the row.
 * @returns The rendered row text.
 */
function row(id, name, guard, config, note) {
  const lines = [];
  if (note !== undefined) lines.push("    # " + note);
  lines.push("    - id: " + id);
  lines.push("      name: '" + name + "'");
  if (guard !== null) lines.push('      disabled: !!js "' + guard + '"');
  if (config !== null && config.length > 0) {
    lines.push("      config:");
    for (const entry of config) lines.push("        " + entry);
  }
  return lines.join(String.fromCharCode(10));
}

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const hit = args.find((a) => a.startsWith("--" + name + "="));
  return hit === undefined ? fallback : hit.slice(name.length + 3);
};
const noTuiClause = args.includes("--no-tui-clause");
const out = flag("out", join(ROOT, "overlay.yml"));

const shipped = readFileSync(join(REPO, "cordis.patch.yml"), "utf8");
const tuiAgent = readTuiClause(shipped, "mpd-agent-team");
const tuiTool = readTuiClause(shipped, "mpd-tool-agent-team");

const composed = (clause, side) => (noTuiClause && side === "new" ? renderGuard(side) : composeTuiAndGeneration(clause, side));

const rows = [
  row("mpd-agent-team", "@deepseek-ai/dsh-experimental-agent-team", composed(tuiAgent, "old"), ["maxMembers: 16", "maxTasks: 256", "maxMessageBytes: 32768", "disposalTimeoutMs: 5000"], "LEGACY set (rc.1 / 0.2.2-rc.1 and older): shipped name + shipped config, unchanged."),
  row("mpd-tool-agent-team", "@deepseek-ai/dsh-experimental-tool-agent-team", composed(tuiTool, "old"), ["freshProvider: mpd-roster", "forkProvider: fork"], "LEGACY tool row: shipped name + shipped config, unchanged."),
  row("mpd-ui-agent-team", "@deepseek-ai/dsh-experimental-client-ui-agent-team", renderGuard("old"), null, "LEGACY UI row: no config, as shipped today."),
  row("mpd-agent-team-rc2", "@deepseek-ai/dsh-agent-team", composed(tuiAgent, "new"), ["maxTasks: 256"], "NEW set (0.2.2-rc.2): renamed package; ONLY maxTasks: 256 (F4 rejects the legacy keys)."),
  row("mpd-tool-agent-team-rc2", "@deepseek-ai/dsh-tool-agent-team", composed(tuiTool, "new"), null, "NEW tool row: NO config key (F4 rejects interrupt/freshProvider/forkProvider)."),
  row("mpd-ui-agent-team-rc2", "@deepseek-ai/dsh-client-ui-agent-team", renderGuard("new"), null, "NEW UI row: no config."),
  row("t1-probe", "t1-probe", null, null, "T1 probe: reports what the loader left enabled/activated. Activates after every row above."),
];

const text = [
  "# T1 mount overlay - the D4 six-row shape, booted with --patch. NOT the shipped patch file.",
  "# Generated by .qa-tmp/t1/make-overlay.mjs from .qa-tmp/t1/predicate.mjs; do not hand-edit.",
  "# tuiClause=" + (noTuiClause ? "off for the NEW rows" : "shipped, on both sides"),
  "- insert:",
  ...rows,
  "",
].join(String.fromCharCode(10) + String.fromCharCode(10));

for (const [label, text_] of [["old", renderGuard("old")], ["new", renderGuard("new")], ["composed-old-agent", composed(tuiAgent, "old")], ["composed-new-agent", composed(tuiAgent, "new")]]) {
  const hazard = hazardOf(text_);
  if (hazard !== "") throw new Error("overlay: guard " + label + " is unsafe: " + hazard);
}
writeFileSync(out, text);
console.log("wrote " + out + " bytes=" + text.length + " tuiClause=" + (noTuiClause ? "new-rows-bare" : "both-sides"));
